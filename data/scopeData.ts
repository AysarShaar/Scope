export function getAllArticles(): ScopeArticle[] {
  return [
    ...scopeHeroArticles,
    ...scopeRightHeroCards,
    ...scopeFeaturedNews,
    scopeInvestigationSpecial,
    ...scopeBreakingArticles,
  ];
}

export function getArticleById(id: string): ScopeArticle | undefined {
  return getAllArticles().find((article) => article.id === id);
}

export function getRelatedArticles(currentId: string, categorySlug?: string, limit: number = 3): ScopeArticle[] {
  const all = getAllArticles().filter((a) => a.id !== currentId);
  if (categorySlug) {
    const sameCat = all.filter((a) => a.categorySlug === categorySlug);
    if (sameCat.length >= limit) return sameCat.slice(0, limit);
  }
  return all.slice(0, limit);
}

